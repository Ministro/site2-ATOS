-- ATOS Telecom - Prêmios com estoque unitário e token único
-- Execute este arquivo no SQL Editor do Supabase antes do deploy.
create extension if not exists pgcrypto;

create table if not exists public.game_premios (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  quantidade integer not null default 0 check (quantidade >= 0),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.game_partidas (
  id uuid primary key default gen_random_uuid(),
  cpf varchar(11) not null,
  premio_resgatado boolean not null default false,
  criado_em timestamptz not null default now()
);
create index if not exists game_partidas_cpf_idx on public.game_partidas(cpf, criado_em desc);

create table if not exists public.game_premios_ganhos (
  id uuid primary key default gen_random_uuid(),
  partida_id uuid not null unique references public.game_partidas(id) on delete restrict,
  premio_id bigint not null references public.game_premios(id) on delete restrict,
  cpf varchar(11) not null,
  premio_nome text not null,
  status text not null default 'pendente',
  criado_em timestamptz not null default now(),
  entregue_em timestamptz
);

alter table public.game_premios_ganhos add column if not exists token_codigo text;
create unique index if not exists game_premios_ganhos_token_uidx
  on public.game_premios_ganhos(token_codigo) where token_codigo is not null;
create index if not exists game_premios_ganhos_cpf_idx on public.game_premios_ganhos(cpf, criado_em desc);

create table if not exists public.game_premio_tokens (
  id uuid primary key default gen_random_uuid(),
  premio_id bigint not null references public.game_premios(id) on delete cascade,
  codigo text not null unique,
  status text not null default 'disponivel' check (status in ('disponivel','reservado','resgatado','cancelado')),
  ganho_id uuid unique references public.game_premios_ganhos(id) on delete set null,
  criado_em timestamptz not null default now(),
  reservado_em timestamptz,
  resgatado_em timestamptz
);
create index if not exists game_premio_tokens_disp_idx on public.game_premio_tokens(premio_id,status);

